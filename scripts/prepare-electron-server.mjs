import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const includeEnv = process.argv.includes("--include-env");
const nextDistDir = resolveNextDistDir();
const standaloneDir = path.join(nextDistDir, "standalone");
const staticDir = path.join(nextDistDir, "static");
const nextServerDir = path.join(nextDistDir, "server");
const bundledDistDirName = path.basename(nextDistDir);
const publicDir = path.join(root, "public");
const outputDir = path.join(root, "dist-electron", "app-server");

if (!fs.existsSync(path.join(standaloneDir, "server.js"))) {
  throw new Error("Missing .next/standalone/server.js. Build with IMAGE_MASTER_STANDALONE=1 first.");
}

fs.rmSync(outputDir, { recursive: true, force: true });
fs.mkdirSync(outputDir, { recursive: true });

copyDir(standaloneDir, outputDir, shouldCopyRuntimePath);
copyOptionalServerRuntimeDir("vendor-chunks");
copyDir(staticDir, path.join(outputDir, bundledDistDirName, "static"), shouldCopyRuntimePath);
if (fs.existsSync(publicDir)) {
  copyDir(publicDir, path.join(outputDir, "public"), shouldCopyRuntimePath);
}

copyFileIfExists(path.join(root, "env.example"), path.join(outputDir, "env.example"));
if (includeEnv) {
  copyFileIfExists(path.join(root, ".env"), path.join(outputDir, ".env"));
}

fs.writeFileSync(
  path.join(outputDir, "ELECTRON_SERVER_README.txt"),
  [
    "Image Master Electron app-server",
    "",
    "This folder is generated by scripts/prepare-electron-server.mjs.",
    includeEnv ? "A local .env file was included for this private test build." : "No .env file was included.",
    "Runtime data is written to the Electron userData directory, not this folder.",
    "",
  ].join("\n"),
);

console.log(JSON.stringify({
  outputDir,
  includeEnv,
  hasEnv: fs.existsSync(path.join(outputDir, ".env")),
}, null, 2));

function copyDir(from, to, filter) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const source = path.join(from, entry.name);
    const target = path.join(to, entry.name);
    if (!filter(source, entry)) continue;
    if (entry.isDirectory()) {
      copyDir(source, target, filter);
    } else if (entry.isSymbolicLink()) {
      const link = fs.readlinkSync(source);
      fs.symlinkSync(link, target);
    } else if (entry.isFile()) {
      fs.copyFileSync(source, target);
    }
  }
}

function shouldCopyRuntimePath(source, entry) {
  const name = entry.name;
  if (name === ".env") return false;
  if (name === ".data" || name === ".data-smoke" || name === ".data-electron-build") return false;
  if (name === "cache" && source.includes(`${path.sep}.next${path.sep}`)) return false;
  if (name.startsWith(".next-dev-") || name.startsWith(".next-real-")) return false;
  if (name === ".playwright-mcp" || name === "test_artifacts" || name === "node_modules/.cache") return false;
  return true;
}

function copyFileIfExists(from, to) {
  if (!fs.existsSync(from)) return;
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function copyOptionalServerRuntimeDir(name) {
  const source = path.join(nextServerDir, name);
  if (!fs.existsSync(source)) return;
  copyDir(source, path.join(outputDir, ".next", "server", name), shouldCopyRuntimePath);
}

function resolveNextDistDir() {
  if (process.env.NEXT_DIST_DIR) return path.resolve(root, process.env.NEXT_DIST_DIR);
  const standaloneBuildDir = path.join(root, ".next-standalone-build");
  if (fs.existsSync(path.join(standaloneBuildDir, "standalone", "server.js"))) {
    return standaloneBuildDir;
  }
  return path.join(root, ".next");
}
